function gallery(kind: ArtKind, tone: string, name: string): ProductImage[] {
  return (['front', 'detail', 'context'] as const).map((view) => ({
    art: { kind, tone, view },
    alt: `${name} — ${view === 'front' ? 'vista frontal' : view === 'detail' ? 'detalhe' : 'em uso'} (imagem ilustrativa)`,
    width: 1200,
    height: 1200,
  }))
}

